//  1. Sum of Two Numbers
 #include <stdio.h>

int main() {
    int a, b;   // Declare two integer variables
    printf("Enter two numbers: ");   // Prompt user for input
    scanf("%d %d", &a, &b);     // Read two integers from user
    printf("Sum = %d\n", a + b);   // Calculate and print the sum
    return 0; 
}
